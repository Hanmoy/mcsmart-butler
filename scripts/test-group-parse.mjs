// 噪音心愿黑名单：这些片段不应作为独立心愿出现在解析结果里（回归护栏）
const NOISE = ['我想', '我要', '想吃', '再来', '一份', '两份', '一个', '两块', '饮料', '单点', '配料', '十块'];

let failures = 0;
let totalWishes = 0;

for (const [name, exp] of Object.entries(CASES)) {
  const { members } = parseGroupText(exp.text);
  const allWishes = members.flatMap((m) => m.wishes);
  totalWishes += allWishes.length;
  const joined = allWishes.join('|');

  if (members.length !== exp.members) {
    console.error(`✗ ${name}: 成员数 ${members.length} ≠ 预期 ${exp.members}`);
    failures++;
  }
  for (const kw of exp.mustMatch) {
    if (!joined.includes(kw)) {
      console.error(`✗ ${name}: 缺失关键心愿「${kw}」`);
      failures++;
    }
  }
  for (const w of allWishes) {
    if (NOISE.includes(w)) {
      console.error(`✗ ${name}: 噪音心愿「${w}」未被过滤`);
      failures++;
    }
  }
}

console.log(`群聊解析回归：${Object.keys(CASES).length} 场景 / ${totalWishes} 心愿 / ${failures} 处失败`);
process.exit(failures > 0 ? 1 : 0);